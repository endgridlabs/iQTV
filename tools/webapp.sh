# What the LG (webos/build.sh) and Samsung (tizen/build.sh) packages share: the settings and the web app's files.
# Sourced by those scripts, not run by itself. Needs bash and a JDK (17+), the same ones build.sh uses.
#
# The settings come from config.properties, the same file as the Android build. --public (the build to share, as
# ./build.sh --public) reads config.example.properties instead: no TMDB key, no name, the region from the TV's
# language. Either way, the TMDB key, name, region and languages can also be set on the TV (EndGrid iQTV+ › Settings),
# and the TV's choice wins.

WEBAPP_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
JAVA="${JAVA_HOME:+$JAVA_HOME/bin/}java"

# webapp_args "$@": sets PUBLIC, PREVIEW (true/false), PROFILE (--sign's) and CONF from the command line.
webapp_args() {
  PUBLIC=false; PREVIEW=false; PROFILE=""; CONF="$WEBAPP_ROOT/config.properties"
  while [ $# -gt 0 ]; do
    case "$1" in
      --public) PUBLIC=true ;;
      --preview) PREVIEW=true ;;
      --config) CONF="${2:?--config needs a file}"; shift ;;
      --sign) PROFILE="${2:?--sign needs a profile name}"; shift ;;
      *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
    shift
  done
  if $PUBLIC; then
    CONF="$WEBAPP_ROOT/config.example.properties"   # never your keys or name in a shared package
  elif [ ! -f "$CONF" ]; then
    cp "$WEBAPP_ROOT/config.example.properties" "$CONF"
    echo "Created config.properties: add your TMDB key there (optional), then build again."
  fi
  command -v "$JAVA" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }
}

# The value of a setting (quotes and backslashes dropped, so it is safe inside a JS string), or $2.
webapp_prop() {
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" "$CONF" | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | tr -d '"\\\r')"
  printf '%s' "${v:-$2}"
}

# webapp_files <folder> <made by>: the app's files in <folder> (emptied first): web/, the settings, the catalogues,
# the symbols and the font.
webapp_files() {
  local dest="$1" by="$2" key="" name="" region hide=false
  rm -rf "$dest" && mkdir -p "$dest/symbols" "$dest/fonts" "$dest/icons"
  cp "$WEBAPP_ROOT"/web/*.html "$WEBAPP_ROOT"/web/*.css "$WEBAPP_ROOT"/web/*.js "$dest/"
  cp "$WEBAPP_ROOT"/web/icons/* "$dest/icons/"
  cp "$WEBAPP_ROOT"/app/assets/symbols/*.png "$WEBAPP_ROOT"/app/assets/symbols/LICENSE* "$dest/symbols/"
  cp "$WEBAPP_ROOT"/app/assets/fonts/InterVariable.ttf "$WEBAPP_ROOT"/app/assets/fonts/OFL.txt "$dest/fonts/"

  region="$(webapp_prop tmdb_region US)"
  if $PUBLIC; then
    region=""   # the TV's own country (from its language) unless set on the TV
  else
    key="$(webapp_prop tmdb_key '')"
    name="$(webapp_prop viewer_name '')"
  fi
  [ "$(webapp_prop hide_animation false)" = "true" ] && hide=true
  {
    printf '/* Generated by %s from %s: edit that file (or the settings on the TV), not this one. */\n' "$by" "$(basename "$CONF")"
    printf 'window.CONFIG = {\n'
    printf '  tmdbKey: "%s",\n' "$key"
    printf '  tmdbRegion: "%s",\n' "$region"
    printf '  contentLanguage: "%s",\n' "$(webapp_prop content_language '')"
    printf '  viewerName: "%s",\n' "$name"
    printf '  language: "%s",\n' "$(webapp_prop language auto)"
    printf '  hideAnimation: %s,\n' "$hide"
    printf '  hideServices: "%s"\n' "$(webapp_prop hide_services '')"
    printf '};\n'
  } > "$dest/config.js"

  # The Android app's catalogues, as they are (each is small).
  {
    printf '/* Generated by %s from app/assets/i18n. */\nwindow.I18N_CATALOGUES = {\n' "$by"
    local first=true f
    for f in "$WEBAPP_ROOT"/app/assets/i18n/*.json; do
      $first || printf ',\n'
      first=false
      printf '"%s": ' "$(basename "$f" .json)"
      tr -d '\r' < "$f"
    done
    printf '\n};\n'
  } > "$dest/i18n.js"
}

# webapp_check_public <folder>: stops if a shared build carries a key or a name.
webapp_check_public() {
  if grep -Eq 'tmdbKey: "[^"]|viewerName: "[^"]' "$1/config.js"; then
    echo "A --public build must not carry a TMDB key or a name. Stopped." >&2
    exit 1
  fi
}

# webapp_has_key <folder>: whether the build carries a TMDB key.
webapp_has_key() {
  grep -q 'tmdbKey: "[^"]' "$1/config.js"
}

# webapp_preview <folder> <preview folder>: a copy to open index.html in a browser (sample apps stand in for the TV's).
webapp_preview() {
  rm -rf "$2" && mkdir -p "$(dirname "$2")" && cp -r "$1" "$2"
  echo "Preview: open $2/index.html in a browser (or serve that folder)."
}
